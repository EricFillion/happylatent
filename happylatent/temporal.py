"""Source-anchored temporal refinement helpers.

This adapts the DFR temporal window recipe to HappyLatent's existing source
latents. Carry frames are independently encoded from the decoded source, rather
than co-generated by a full DFR base pass. Windows are bounded to one source
segment so long timelines do not create progressively larger diffusion inputs.
"""
from __future__ import annotations

import json
import math

TEMPORAL_SIGMAS = "0.975, 0.909375, 0.725, 0.421875, 0"


def temporal_layout(source_frames):
    """Return bounded windows without padding/changing the base generation."""
    if isinstance(source_frames, bool) or not isinstance(source_frames, int) or source_frames < 9 or (source_frames - 1) % 8:
        raise ValueError("Temporal refinement requires an 8n+1 source canvas of at least 9 frames.")
    content = source_frames - 1
    # Official DFR's least-padding choice; retain the existing canvas and allow
    # a final short x8 segment instead of regenerating a padded source.
    segment = min((24, 32), key=lambda n: ((-content) % n, -n))
    ends = list(range(segment, content, segment)) + [content]
    result, left, previous_midpoint = [], 0, None
    for index, right in enumerate(ends):
        midpoint = left + right  # target position = 2 * source midpoint
        origin = previous_midpoint if index else 0
        seam = 2 * left
        pinned = 1 + (seam - origin) // 8 if index else 0
        result.append({"index": index, "source_frames": source_frames,
            "start": origin, "end": 2 * right, "seam": seam,
            "pinned": pinned, "anchor": 2 * right, "midpoint": midpoint,
            "frames": 2 * right - origin + 1})
        left, previous_midpoint = right, midpoint
    return result


def source_guide_positions(layout):
    return sorted({window[key] for window in layout for key in ("anchor", "midpoint")})


def conditioning_fps(playback_fps):
    return 60.0 if playback_fps > 30 else float(playback_fps)


def _torch():
    import torch
    return torch


def _samples(latent, name, ndim):
    torch = _torch()
    value = latent.get("samples") if isinstance(latent, dict) else None
    if not torch.is_tensor(value) or value.is_nested or value.ndim != ndim or any(size < 1 for size in value.shape):
        raise ValueError(f"Temporal refinement: {name} needs a nonempty plain {ndim}D samples tensor.")
    if value.shape[0] != 1:
        raise ValueError(f"Temporal refinement: {name} requires batch size 1.")
    return value


def _plain(latent):
    return {k: v for k, v in latent.items() if k not in (
        "samples", "noise_mask", "generated_keyframe_indices", "generated_keyframe_num_frames")}


def _plan(value):
    window = json.loads(value) if isinstance(value, str) else value
    try:
        expected = temporal_layout(window["source_frames"])[window["index"]]
    except (KeyError, IndexError, TypeError, ValueError) as error:
        raise ValueError("Temporal refinement: invalid window plan.") from error
    if window != expected:
        raise ValueError("Temporal refinement: window plan does not match the source canvas.")
    return window


def _same_grid(value, reference, name):
    if value.shape[:2] != reference.shape[:2] or value.shape[3:] != reference.shape[3:]:
        raise ValueError(f"Temporal refinement: {name} has a different video grid.")


def _plane(guides, position, reference):
    samples = _samples(guides, "source guides", 5)
    positions = guides.get("generated_keyframe_indices")
    if not isinstance(positions, (list, tuple)) or len(positions) != samples.shape[2] or len(set(positions)) != len(positions) or position not in positions:
        raise ValueError(f"Temporal refinement: missing source guide at output frame {position}.")
    _same_grid(samples, reference, "source guides")
    i = positions.index(position)
    return samples[:, :, i:i + 1].to(reference).clone()


class _Internal:
    CATEGORY = "HappyLatent/internal"
    DEPRECATED = True
    FUNCTION = "execute"


class HappyLatentTemporalSourceGuides(_Internal):
    RETURN_TYPES = ("LATENT",)

    @classmethod
    def INPUT_TYPES(cls):
        return {"required": {"images": ("IMAGE",), "vae": ("VAE",),
            "source_frames": ("INT", {"min": 9, "max": 1201})}}

    def execute(self, images, vae, source_frames):
        torch = _torch()
        positions = source_guide_positions(temporal_layout(source_frames))
        if not torch.is_tensor(images) or images.ndim != 4 or images.shape[0] != source_frames:
            raise ValueError(f"Temporal refinement: expected {source_frames} decoded source frames.")
        planes = []
        for position in positions:
            frame = position // 2
            encoded = vae.encode(images[frame:frame + 1, :, :, :3])
            value = _samples({"samples": encoded}, "encoded source guide", 5)
            if value.shape[2] != 1:
                raise ValueError("Temporal refinement: the video VAE must encode one image as one latent plane.")
            if planes:
                _same_grid(value, planes[0], "encoded source guide")
            planes.append(value)
        return ({"samples": torch.cat(planes, dim=2), "generated_keyframe_indices": positions,
                 "generated_keyframe_num_frames": 2 * source_frames - 1},)


class HappyLatentTemporalPrepare(_Internal):
    RETURN_TYPES = ("LATENT", "LATENT", "LATENT")
    RETURN_NAMES = ("video", "anchor", "midpoint")

    @classmethod
    def INPUT_TYPES(cls):
        return {"required": {"upscaled": ("LATENT",), "guides": ("LATENT",), "window": ("STRING",)},
                "optional": {"previous": ("LATENT",)}}

    def execute(self, upscaled, guides, window, previous=None):
        torch = _torch()
        window = _plan(window)
        raw = _samples(upscaled, "upscaled video", 5)
        expected = (window["source_frames"] - 1) // 4 + 1
        if raw.shape[2] != expected:
            raise ValueError(f"Temporal refinement: the temporal upscaler returned {raw.shape[2]} latent frames; expected {expected}.")
        if guides.get("generated_keyframe_num_frames") != 2 * window["source_frames"] - 1:
            raise ValueError("Temporal refinement: source guides belong to a different canvas.")
        end = window["end"] // 8 + 1
        if window["index"] == 0:
            if previous is not None:
                raise ValueError("Temporal refinement: the first window cannot have a previous result.")
            samples = raw[:, :, :end].clone()
        else:
            prior = _samples(previous, "previous refined video", 5)
            _same_grid(prior, raw, "previous refined video")
            prior_window = temporal_layout(window["source_frames"])[window["index"] - 1]
            if prior.shape[2] != (prior_window["frames"] - 1) // 8 + 1:
                raise ValueError("Temporal refinement: the previous result does not match the preceding window.")
            start = window["start"] // 8 + 1
            offset = start - prior_window["start"] // 8
            count = window["pinned"] - 1
            if offset < 0 or offset + count > prior.shape[2]:
                raise ValueError("Temporal refinement: the pinned prefix falls outside the preceding window.")
            plane = _plane(guides, window["start"], raw)
            samples = torch.cat([plane, raw[:, :, start:end]], dim=2)
            samples[:, :, :window["pinned"]] = torch.cat([plane, prior[:, :, offset:offset + count].to(raw)], dim=2)
        mask = torch.ones((1, 1, samples.shape[2], 1, 1), device=samples.device, dtype=torch.float32)
        mask[:, :, :window["pinned"]] = 0
        video = _plain(upscaled)
        video.update(samples=samples, noise_mask=mask)
        def guide(key):
            return {"samples": _plane(guides, window[key], raw),
                    "generated_keyframe_indices": [window[key] - window["start"]],
                    "generated_keyframe_num_frames": window["frames"]}
        return video, guide("anchor"), guide("midpoint")


def audio_for_window(source_audio, window, playback_fps, source_duration, cond_fps):
    torch = _torch()
    window = _plan(window)
    audio = _samples(source_audio, "source audio", 4)
    if not all(math.isfinite(v) and v > 0 for v in (playback_fps, source_duration, cond_fps)):
        raise ValueError("Temporal refinement: audio timing values must be positive and finite.")
    count = max(1, round(window["frames"] / cond_fps * 25.0))
    start = window["start"] / playback_fps / source_duration * audio.shape[2]
    end = (window["start"] + window["frames"]) / playback_fps / source_duration * audio.shape[2]
    positions = (start + (end - start) / count * torch.arange(count, device=audio.device, dtype=torch.float32)).clamp(0, audio.shape[2] - 1)
    lo = positions.floor().long()
    hi = (lo + 1).clamp(max=audio.shape[2] - 1)
    weight = (positions - lo.float()).to(audio.dtype).view(1, 1, -1, 1)
    samples = audio[:, :, lo] * (1 - weight) + audio[:, :, hi] * weight
    result = _plain(source_audio)
    result.update(samples=samples, noise_mask=torch.zeros_like(samples), type="audio")
    return result


class HappyLatentTemporalAudio(_Internal):
    RETURN_TYPES = ("LATENT",)

    @classmethod
    def INPUT_TYPES(cls):
        return {"required": {"source_audio": ("LATENT",), "window": ("STRING",),
            "playback_fps": ("FLOAT", {"min": 1}), "source_duration": ("FLOAT", {"min": 0.001}),
            "cond_fps": ("FLOAT", {"min": 1})}}

    def execute(self, source_audio, window, playback_fps, source_duration, cond_fps):
        return (audio_for_window(source_audio, window, playback_fps, source_duration, cond_fps),)


def join_temporal_windows(source_frames, windows):
    """Concatenate owned slices once; never cache successively larger prefixes."""
    torch = _torch()
    layout = temporal_layout(source_frames)
    if not isinstance(windows, dict) or set(windows) != {f"window{i}" for i in range(len(layout))}:
        raise ValueError("Temporal refinement: all refined windows are required for final stitching.")
    pieces, reference = [], None
    for window in layout:
        latent = windows[f"window{window['index']}"]
        samples = _samples(latent, "refined window", 5)
        if samples.shape[2] != (window["frames"] - 1) // 8 + 1:
            raise ValueError("Temporal refinement: strip guide frames before stitching the window.")
        if reference is None:
            reference = samples
        else:
            _same_grid(samples, reference, "refined window")
        pieces.append(samples[:, :, window["pinned"]:].to(reference))
    result = torch.cat(pieces, dim=2)
    if result.shape[2] != (source_frames - 1) // 4 + 1:
        raise ValueError("Temporal refinement: stitched video does not match the output canvas.")
    return {"samples": result}


def native_temporal_join_node():
    from comfy_api.latest import io

    class HappyLatentTemporalJoin(io.ComfyNode):
        @classmethod
        def define_schema(cls):
            return io.Schema(node_id="HappyLatentTemporalJoin", category="HappyLatent/internal", is_deprecated=True,
                inputs=[io.Int.Input("source_frames", min=9, max=1201), io.Autogrow.Input("windows",
                    template=io.Autogrow.TemplatePrefix(io.Latent.Input("window"), prefix="window", min=1, max=50))],
                outputs=[io.Latent.Output()])

        @classmethod
        def execute(cls, source_frames, windows):
            return io.NodeOutput(join_temporal_windows(source_frames, windows))

    return HappyLatentTemporalJoin


class HappyLatentTemporalAnchorAttention(_Internal):
    RETURN_TYPES = ("CONDITIONING", "CONDITIONING")

    @classmethod
    def INPUT_TYPES(cls):
        return {"required": {"positive": ("CONDITIONING",), "negative": ("CONDITIONING",)}}

    @staticmethod
    def adjust(conditioning):
        result = []
        for embedding, metadata in conditioning:
            entries = metadata.get("guide_attention_entries")
            if not isinstance(entries, (list, tuple)) or len(entries) != 1 or not math.isclose(entries[0].get("strength", -1), 0.95, abs_tol=1e-7):
                raise ValueError("Temporal refinement: expected exactly one fresh source anchor at strength 0.95.")
            result.append([embedding, {**metadata, "guide_attention_entries": [{**entries[0], "strength": 1.0}]}])
        if not result:
            raise ValueError("Temporal refinement: missing text conditioning.")
        return result

    def execute(self, positive, negative):
        return self.adjust(positive), self.adjust(negative)


TEMPORAL_NODE_CLASSES = (HappyLatentTemporalSourceGuides, HappyLatentTemporalPrepare,
    HappyLatentTemporalAudio, HappyLatentTemporalAnchorAttention)


def compile_temporal_refinement(node, *, source, upscaled, source_audio, source_frames,
                                fps, seed, positive, negative, model, vae, sampler, sigmas):
    """Expand the fixed-source-guide recipe using native sampling/guide nodes."""
    layout = temporal_layout(source_frames)
    decoded = node("temporal_source_decode", "HappyLatentDecode", samples=source, vae=vae)
    guides = node("temporal_source_guides", "HappyLatentTemporalSourceGuides",
                  images=decoded, vae=vae, source_frames=source_frames)
    opening = node("temporal_opening_frame", "ImageFromBatch", image=decoded, batch_index=0, length=1)
    playback_fps = 2 * fps
    cond_fps = conditioning_fps(playback_fps)
    conditioning = node("temporal_conditioning", "LTXVConditioning", positive=positive,
                        negative=negative, frame_rate=cond_fps)
    previous = None
    windows = {}
    for window in layout:
        label = f"temporal_window_{window['index']}_"
        encoded_window = json.dumps(window, sort_keys=True)
        options = {"previous": previous} if previous is not None else {}
        prepared = node(label + "prepare", "HappyLatentTemporalPrepare", upscaled=upscaled,
                        guides=guides, window=encoded_window, **options)
        anchor = node(label + "anchor", "LTXVGeneratedKeyframesToGuides", positive=conditioning,
                      negative=[conditioning[0], 1], latent=prepared, keyframes=[prepared[0], 1],
                      vae=vae, strength=0.95)
        attention = node(label + "anchor_attention", "HappyLatentTemporalAnchorAttention",
                         positive=anchor, negative=[anchor[0], 1])
        p, n, video = attention, [attention[0], 1], [anchor[0], 2]
        if window["index"] == 0:
            opened = node(label + "opening", "LTXVAddGuide", positive=p, negative=n,
                          latent=video, vae=vae, image=opening, frame_idx=0, strength=1.0)
            p, n, video = opened, [opened[0], 1], [opened[0], 2]
        midpoint = node(label + "midpoint", "LTXVGeneratedKeyframesToGuides", positive=p,
                        negative=n, latent=video, keyframes=[prepared[0], 2], vae=vae, strength=1.0)
        p, n, video = midpoint, [midpoint[0], 1], [midpoint[0], 2]
        if source_audio is not None:
            audio = node(label + "audio", "HappyLatentTemporalAudio", source_audio=source_audio,
                         window=encoded_window, playback_fps=playback_fps,
                         source_duration=source_frames / fps, cond_fps=cond_fps)
            video = node(label + "av", "LTXVConcatAVLatent", video_latent=video, audio_latent=audio)
        noise = node(label + "noise", "RandomNoise", noise_seed=(seed + 1000 + window["index"]) % 2**53)
        guider = node(label + "guider", "LTXVDualCFGGuider", model=model, positive=p, negative=n,
                      video_cfg=1.0, audio_cfg=1.0)
        refined = node(label + "sample", "SamplerCustomAdvanced", noise=noise, guider=guider,
                       sampler=sampler, sigmas=sigmas, latent_image=video)
        if source_audio is not None:
            refined = node(label + "separate", "LTXVSeparateAVLatent", av_latent=refined)
        cropped = node(label + "crop_guides", "LTXVCropGuides", positive=p, negative=n, latent=refined)
        previous = [cropped[0], 2]
        windows[f"windows.window{window['index']}"] = previous
    return node("temporal_refine", "HappyLatentTemporalJoin", source_frames=source_frames, **windows)
